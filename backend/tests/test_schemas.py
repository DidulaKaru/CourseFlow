def test_openapi_schema_contains_curriculum_definitions():
    """Verify OpenAPI schema generated by FastAPI contains all curriculum models in camelCase."""
    schema = app.openapi()
    schemas = schema["components"]["schemas"]

    required_models = [
        "Course",
        "CourseRuleNode",
        "CreditThresholdRuleNode",
        "LogicalRuleNode",
        "CreditDistribution",
        "DegreeProgram",
        "CourseType",
        "SemesterTerm",
    ]
    for model_name in required_models:
        assert model_name in schemas, f"Missing {model_name} in OpenAPI schemas"

    course_props = schemas["Course"]["properties"]
    assert "totalCredits" in course_props
    assert "creditDistribution" in course_props
    assert "recommendedSemester" in course_props
    assert "prerequisiteRule" in course_props

    program_props = schemas["DegreeProgram"]["properties"]
    assert "totalCreditsRequired" in program_props
    assert "minCreditsPerSemester" in program_props
    assert "maxCreditsPerSemester" in program_props
