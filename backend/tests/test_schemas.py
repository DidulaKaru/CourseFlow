"""Tests for curriculum Pydantic schemas and contract fidelity."""

import json
from pathlib import Path

import pytest
from app.main import app
from app.schemas.curriculum import (
    Course,
    CourseRuleNode,
    CourseType,
    CreditDistribution,
    CreditThresholdRuleNode,
    DegreeProgram,
    LogicalRuleNode,
    SemesterTerm,
)
from pydantic import ValidationError


def test_course_rule_node_serialization():
    """Verify CourseRuleNode supports camelCase alias and defaults."""
    node = CourseRuleNode.model_validate({"courseId": "EC101"})
    assert node.type == "COURSE"
    assert node.course_id == "EC101"

    dumped = node.model_dump(by_alias=True)
    assert dumped == {"type": "COURSE", "courseId": "EC101"}


def test_credit_threshold_node():
    """Verify CreditThresholdRuleNode validates positive credits."""
    node = CreditThresholdRuleNode.model_validate({"minCredits": 30})
    assert node.type == "CREDIT_THRESHOLD"
    assert node.min_credits == 30

    with pytest.raises(ValidationError):
        CreditThresholdRuleNode.model_validate({"minCredits": -5})


def test_recursive_logical_rule_node():
    """Verify compound recursive AST parses correctly: (EC101 AND EC102) OR (EC105 AND Credits >= 30)."""
    raw_ast = {
        "type": "OR",
        "children": [
            {
                "type": "AND",
                "children": [
                    {"type": "COURSE", "courseId": "EC101"},
                    {"type": "COURSE", "courseId": "EC102"},
                ],
            },
            {
                "type": "AND",
                "children": [
                    {"type": "COURSE", "courseId": "EC105"},
                    {"type": "CREDIT_THRESHOLD", "minCredits": 30},
                ],
            },
        ],
    }

    ast = LogicalRuleNode.model_validate(raw_ast)
    assert ast.type == "OR"
    assert len(ast.children) == 2
    assert isinstance(ast.children[0], LogicalRuleNode)
    assert ast.children[0].type == "AND"

    # Verify round-trip serialization by alias
    dumped = ast.model_dump(by_alias=True)
    assert dumped == raw_ast


def test_credit_distribution_validation():
    """Verify CreditDistribution enforces bounds on semesterIndex and creditsAllocated."""
    dist = CreditDistribution.model_validate(
        {"semesterIndex": 7, "creditsAllocated": 3}
    )
    assert dist.semester_index == 7
    assert dist.credits_allocated == 3

    # Semester index must be between 1 and 8
    with pytest.raises(ValidationError):
        CreditDistribution.model_validate({"semesterIndex": 0, "creditsAllocated": 3})

    with pytest.raises(ValidationError):
        CreditDistribution.model_validate({"semesterIndex": 9, "creditsAllocated": 3})


def test_mock_course_parsing():
    """Verify Course model parses the official mock_course.json data."""
    repo_root = Path(__file__).resolve().parent.parent.parent
    mock_file = repo_root / "src" / "data" / "mock_course.json"
    assert mock_file.exists(), f"mock_course.json not found at {mock_file}"

    with open(mock_file, encoding="utf-8") as f:
        mock_data = json.load(f)

    course = Course.model_validate(mock_data)
    assert course.id == "CE4001"
    assert course.code == "CE4001"
    assert course.type == CourseType.CAPSTONE
    assert course.total_credits == 6
    assert course.duration_semesters == 2
    assert course.recommended_semester == 7
    assert len(course.credit_distribution) == 2
    assert course.offered_semesters == [SemesterTerm.BOTH]
    assert course.corequisites == ["CE4002"]

    # Verify AST structure
    assert course.prerequisite_rule is not None
    assert isinstance(course.prerequisite_rule, LogicalRuleNode)
    assert course.prerequisite_rule.type == "AND"
    assert len(course.prerequisite_rule.children) == 3

    # Serialized keys must match source JSON keys exactly
    dumped = course.model_dump(by_alias=True)
    assert set(dumped.keys()) == set(mock_data.keys())


